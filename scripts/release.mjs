// Release configuration shared by the Vite build (vite.config.ts) and the
// deployment check (scripts/check-dist.mjs). Plain ESM so Node can run it
// directly. Everything here is public: there are no secrets in a static site.

/** Build channels. "beta" is the default so nothing is indexed by accident. */
export const CHANNELS = ['beta', 'production'];

/** GoatCounter's documented count endpoint, e.g. https://mycode.goatcounter.com/count */
export const ANALYTICS_ENDPOINT_PATTERN = /^https:\/\/[a-z0-9][a-z0-9-]{0,62}\.goatcounter\.com\/count$/;

/**
 * Reads the public build settings from environment variables.
 * VITE_RELEASE_CHANNEL   beta (default) | production
 * VITE_ANALYTICS_ENDPOINT  optional GoatCounter /count URL; analytics are off when empty
 * VITE_FEEDBACK_URL        optional https link to the beta questionnaire
 */
export function resolveReleaseConfig(env) {
  const errors = [];
  const channel = (env.VITE_RELEASE_CHANNEL || 'beta').trim();
  if (!CHANNELS.includes(channel)) errors.push(`VITE_RELEASE_CHANNEL must be one of ${CHANNELS.join(', ')} (got "${channel}").`);

  const analyticsEndpoint = (env.VITE_ANALYTICS_ENDPOINT || '').trim();
  if (analyticsEndpoint && !ANALYTICS_ENDPOINT_PATTERN.test(analyticsEndpoint)) {
    errors.push('VITE_ANALYTICS_ENDPOINT must look like https://<code>.goatcounter.com/count');
  }

  const feedbackUrl = (env.VITE_FEEDBACK_URL || '').trim();
  if (feedbackUrl) {
    let ok = false;
    try {
      ok = new URL(feedbackUrl).protocol === 'https:';
    } catch {
      ok = false;
    }
    if (!ok) errors.push('VITE_FEEDBACK_URL must be an https:// link.');
  }

  return {
    channel: CHANNELS.includes(channel) ? channel : 'beta',
    analyticsEndpoint: analyticsEndpoint && ANALYTICS_ENDPOINT_PATTERN.test(analyticsEndpoint) ? analyticsEndpoint : '',
    feedbackUrl: errors.some((e) => e.startsWith('VITE_FEEDBACK_URL')) ? '' : feedbackUrl,
    errors,
  };
}

/**
 * Used by vite.config.ts: passes the short commit id from Cloudflare Pages or
 * GitHub Actions to the app (shown in the footer), then resolves the config from
 * the process environment plus Vite's .env files.
 */
export function buildEnvironment(loadedEnv = {}) {
  const commit = (process.env.CF_PAGES_COMMIT_SHA || process.env.GITHUB_SHA || '').slice(0, 7);
  if (commit && !process.env.VITE_BUILD_COMMIT) process.env.VITE_BUILD_COMMIT = commit;
  return resolveReleaseConfig({ ...process.env, ...loadedEnv });
}

export function contentSecurityPolicy(config) {
  const connect = ["'self'"];
  if (config.analyticsEndpoint) connect.push(new URL(config.analyticsEndpoint).origin);
  return [
    "default-src 'self'",
    "script-src 'self'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src ${connect.join(' ')}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/** Cloudflare Pages `_headers` file. */
export function headersFile(config) {
  const lines = [
    '# Generated by scripts/release.mjs during the build. Do not edit dist/_headers by hand.',
    '/*',
    `  Content-Security-Policy: ${contentSecurityPolicy(config)}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=()',
    '  X-Frame-Options: DENY',
    '  Cross-Origin-Opener-Policy: same-origin',
  ];
  if (config.channel !== 'production') lines.push('  X-Robots-Tag: noindex, nofollow');
  lines.push('', '/assets/*', '  Cache-Control: public, max-age=31536000, immutable', '');
  return lines.join('\n');
}

/** robots.txt: the beta asks every crawler to stay out; production allows crawling. */
export function robotsFile(config) {
  return config.channel === 'production'
    ? 'User-agent: *\nAllow: /\n'
    : '# Private beta: please do not crawl or index.\nUser-agent: *\nDisallow: /\n';
}

/** <meta name="robots"> for index.html, or null for production. */
export function robotsMeta(config) {
  return config.channel === 'production' ? null : 'noindex, nofollow';
}
